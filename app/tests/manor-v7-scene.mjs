async function request(path, body, expected = 200, session = cookie, headers = {}) {
  const response = await fetch(`${base}${path}`, { method: body === undefined ? "GET" : "POST", headers: {
    ...(session ? { cookie: session } : {}), ...(body === undefined ? {} : { "content-type": "application/json", "x-manor-owner": owner }), ...headers,
  }, ...(body === undefined ? {} : { body: JSON.stringify(body) }), signal: AbortSignal.timeout(60000) });
  const text = await response.text();
  assert.equal(response.status, expected, `${path}: ${text.slice(0, 800)}`);
  if (expected === 200) assert.match(response.headers.get("cache-control") || "", /no-store/);
  return JSON.parse(text);
}

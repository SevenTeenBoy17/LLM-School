import assert from "node:assert/strict";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { startManorServer, launchManorBrowser, assertNoHorizontalOverflow, RESULTS_DIR } from "./manor-v5-helpers.mjs";

const results = join(RESULTS_DIR, "agent-workbench");
mkdirSync(results, { recursive: true });
const originalTsconfig = readFileSync(new URL("../tsconfig.json", import.meta.url), "utf8");
const originalNextEnv = readFileSync(new URL("../next-env.d.ts", import.meta.url), "utf8");
const server = await startManorServer("agent-workbench-ui");
let browser;
const report = { checks: [], errors: [] };
const pass = message => { report.checks.push(message); console.log(`PASS ${message}`); };
try {
  browser = await launchManorBrowser();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, reducedMotion: "reduce", permissions: ["clipboard-read", "clipboard-write"] });
  const page = await context.newPage();
  page.on("pageerror", e => report.errors.push(e.message));
  assert.ok((await page.request.post(`${server.base}/api/auth/login`, { data: { username: "teacher", password: "Teacher@123" } })).ok());
  await page.goto(`${server.base}/agent`, { waitUntil: "networkidle" });
  const root = page.getByTestId("agent-workbench");
  const library = page.getByTestId("agent-template-library");
  assert.equal(await library.locator("article").count(), 16);
  await assertNoHorizontalOverflow(page, "agent desktop");
  await page.screenshot({ path: join(results, "desktop.png"), fullPage: true });
  const broken = await library.locator("img").evaluateAll(images => images.filter(img => !img.complete || !img.naturalWidth).map(img => img.src));
  assert.deepEqual(broken, []);
  pass("16 task cards and existing semantic assets; desktop has no overflow");
  await root.getByLabel("搜索智能体").fill("量规");
  assert.ok(await library.locator("article").count() >= 1);
  await root.getByLabel("搜索智能体").fill("nomatch-xyz");
  await library.getByText("没有匹配的场景").waitFor();
  await library.getByRole("button", { name: "清除筛选" }).click();
  await library.getByRole("button", { name: /教研发展/ }).click();
  assert.equal(await library.locator("article").count(), 3);
  await library.getByRole("button", { name: /全部场景/ }).click();
  const detail = library.getByRole("button", { name: "查看与使用：课时教学设计助手", exact: true });
  await detail.click();
  const dialog = page.getByRole("dialog");
  await dialog.getByText("任务指令", { exact: true }).click();
  await dialog.getByRole("button", { name: "复制指令" }).click();
  assert.ok((await page.evaluate(() => navigator.clipboard.readText())).includes("课时教学设计助手"));
  await page.screenshot({ path: join(results, "detail.png"), fullPage: true });
  await page.keyboard.press("Escape");
  assert.ok(await detail.evaluate(el => document.activeElement === el));
  pass("search, categories, empty reset, prompt copy, Escape and focus restoration");

  await page.evaluate(() => {
    window.originalClipboardWrite = navigator.clipboard.writeText.bind(navigator.clipboard);
    navigator.clipboard.writeText = () => new Promise(resolve => { window.finishOldCopy = resolve; });
  });
  await detail.click();
  await dialog.getByText("任务指令", { exact: true }).click();
  await dialog.getByRole("button", { name: "复制指令" }).click();
  await page.keyboard.press("Escape");
  await detail.click();
  await dialog.getByText("任务指令", { exact: true }).click();
  await page.evaluate(() => { window.finishOldCopy(); navigator.clipboard.writeText = window.originalClipboardWrite; });
  assert.equal(await dialog.getByRole("button", { name: "已复制", exact: true }).count(), 0);
  await page.keyboard.press("Escape");
  pass("late clipboard completion cannot update a reopened detail session");

  await detail.click();
  let createRequests = 0;
  let release;
  await page.route("**/api/agents", async route => {
    if (route.request().method() !== "POST") return route.continue();
    createRequests++;
    await new Promise(resolve => { release = resolve; });
    await route.fulfill({ status: 403, json: { error: "test_forbidden" } });
  });
  await dialog.getByRole("button", { name: "创建草稿并试用" }).click();
  await dialog.getByRole("progressbar").waitFor();
  assert.equal(await dialog.getByRole("progressbar").getAttribute("aria-valuenow"), null);
  assert.ok(await dialog.getByRole("button", { name: "创建中", exact: true }).isDisabled());
  release();
  await dialog.getByRole("alert").waitFor();
  assert.equal(createRequests, 1);
  await page.unroute("**/api/agents");
  pass("pending progress is indeterminate, duplicate submit disabled, explicit permission rejection is recoverable");

  await page.route("**/api/agents", async route => {
    if (route.request().method() !== "POST") return route.continue();
    await new Promise(resolve => { release = resolve; });
    await route.fulfill({ status: 503, json: { error: "test_cancelled" } }).catch(() => {});
  });
  await dialog.getByRole("button", { name: "创建草稿并试用" }).click();
  await dialog.getByRole("button", { name: "停止等待", exact: true }).click();
  await dialog.getByRole("alert").filter({ hasText: "保存结果未确认" }).waitFor();
  assert.ok(await dialog.getByRole("button", { name: "创建草稿并试用" }).isDisabled());
  assert.equal(await dialog.getByRole("link", { name: "自定义后创建" }).getAttribute("aria-disabled"), "true");
  release();
  await page.unroute("**/api/agents");
  await dialog.getByRole("button", { name: "返回目录" }).click();
  await detail.click();
  assert.ok(await dialog.getByRole("button", { name: "创建草稿并试用" }).isDisabled());
  await dialog.getByRole("button", { name: "查看现有智能体", exact: true }).click();
  await root.getByRole("button", { name: /现有智能体/ }).waitFor();
  await root.getByRole("button", { name: /场景助手/ }).click();
  await detail.click();
  assert.ok(await dialog.getByRole("button", { name: "创建草稿并试用" }).isDisabled());
  await dialog.getByRole("button", { name: "已核对目录，允许重新创建" }).click();
  pass("stop waiting preserves uncertain outcome across reopened details and directory visits until explicit acknowledgement");
  await page.route("**/api/agents", route => route.request().method() === "POST"
    ? route.fulfill({ status: 502, json: { error: "test_gateway_failure" } }) : route.continue());
  await dialog.getByRole("button", { name: "创建草稿并试用" }).click();
  await dialog.getByRole("alert").filter({ hasText: "保存结果未确认" }).waitFor();
  await page.unroute("**/api/agents");
  await dialog.getByRole("button", { name: "返回目录" }).click();
  await detail.click();
  assert.ok(await dialog.getByRole("button", { name: "创建草稿并试用" }).isDisabled());
  await dialog.getByRole("button", { name: "查看现有智能体", exact: true }).click();
  await library.waitFor({ state: "hidden" });
  await root.getByRole("button", { name: /场景助手/ }).click();
  await detail.click();
  await dialog.getByRole("button", { name: "已核对目录，允许重新创建" }).click();
  pass("gateway errors retain pending status; repeated inspect-existing action always changes the view");
  const createdResponse = page.waitForResponse(res => res.url().endsWith("/api/agents") && res.request().method() === "POST");
  await dialog.getByRole("button", { name: "创建草稿并试用" }).click();
  const created = await (await createdResponse).json();
  assert.equal(created.agent.status, "draft");
  assert.equal(created.agent.calls, 0); assert.equal(created.agent.score, 0);
  assert.equal(created.agent.knowledgeBase, "");
  assert.ok(created.agent.systemPrompt.includes("课时教学设计助手"));
  await page.waitForURL(`**/chat?agent=${created.agent.id}`);
  await page.getByRole("textbox").first().waitFor();
  pass("real API creates owner draft with full instructions, zero metrics, no KB; navigates to actual chat");

  const id = created.agent.id;
  let response = await page.request.get(`${server.base}/api/agents/${id}`);
  assert.equal((await response.json()).agent.systemPrompt, created.agent.systemPrompt);
  response = await page.request.put(`${server.base}/api/agents/${id}`, { data: { description: "updated" } });
  assert.equal((await response.json()).agent.systemPrompt, created.agent.systemPrompt);
  response = await page.request.put(`${server.base}/api/agents/${id}`, { data: { systemPrompt: "x".repeat(6001) } });
  assert.equal(response.status(), 400);
  response = await page.request.put(`${server.base}/api/agents/${id}`, { data: { systemPrompt: "" } });
  assert.equal((await response.json()).agent.systemPrompt, "");
  await page.request.put(`${server.base}/api/agents/${id}`, { data: { systemPrompt: created.agent.systemPrompt } });
  assert.ok((await page.request.patch(`${server.base}/api/agents/${id}`, { data: { status: "review" } })).ok());
  assert.equal((await page.request.put(`${server.base}/api/agents/${id}`, { data: { systemPrompt: "changed" } })).status(), 409);
  for (const patch of [{ name: "changed" }, { description: "changed" }, { knowledgeBase: "changed" }, { recommendedModel: "minimax" }, { capabilities: ["changed"] }]) {
    assert.equal((await page.request.put(`${server.base}/api/agents/${id}`, { data: patch })).status(), 409);
  }
  assert.ok((await page.request.put(`${server.base}/api/agents/${id}`, { data: { icon: "Bot" } })).ok());
  await page.request.patch(`${server.base}/api/agents/${id}`, { data: { status: "draft" } });
  const other = await browser.newContext();
  assert.ok((await other.request.post(`${server.base}/api/auth/login`, { data: { username: "student", password: "Student@123" } })).ok());
  assert.equal((await other.request.get(`${server.base}/api/agents/${id}`)).status(), 404);
  assert.ok(!(await (await other.request.get(`${server.base}/api/agents`)).json()).agents.some(a => a.id === id));
  assert.equal((await other.request.put(`${server.base}/api/agents/${id}`, { data: { systemPrompt: "hijack" } })).status(), 403);
  await other.close();
  pass("instruction read/update/clear/preserve/length contract, review lock and other-user isolation");

  let editPuts = 0;
  let releaseEdit;
  const editGate = new Promise(resolve => { releaseEdit = resolve; });
  page.on("request", req => { if (req.method() === "PUT" && req.url().endsWith(`/api/agents/${id}`)) editPuts++; });
  await page.route(`**/api/agents/${id}`, async route => {
    if (route.request().method() !== "GET") return route.continue();
    await editGate;
    await route.fulfill({ status: 503, json: { error: "load_failed" } }).catch(() => {});
  });
  await page.goto(`${server.base}/agent/new?id=${id}`, { waitUntil: "domcontentloaded" });
  await page.getByRole("progressbar").waitFor();
  assert.equal(await page.getByRole("button", { name: "保存", exact: true }).count(), 0);
  assert.equal(await page.getByRole("button", { name: "发送测试问题" }).count(), 0);
  releaseEdit();
  await page.getByRole("alert").filter({ hasText: "未能载入" }).waitFor();
  assert.equal(editPuts, 0);
  await page.unroute(`**/api/agents/${id}`);
  await page.getByRole("button", { name: "重新载入" }).click();
  await page.getByLabel("智能体名称", { exact: true }).waitFor();
  await page.getByLabel("简介", { exact: true }).fill("保留本地未保存的输入");
  await page.request.patch(`${server.base}/api/agents/${id}`, { data: { status: "review" } });
  await page.getByRole("button", { name: "保存", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "状态已变更" }).waitFor();
  assert.equal(await page.getByLabel("简介", { exact: true }).inputValue(), "保留本地未保存的输入");
  await page.reload({ waitUntil: "networkidle" });
  await page.getByRole("alert").filter({ hasText: "运行配置不可直接修改" }).waitFor();
  assert.equal(await page.getByRole("button", { name: "保存", exact: true }).count(), 0);
  await page.request.patch(`${server.base}/api/agents/${id}`, { data: { status: "draft" } });
  pass("slow/failed edit loads never submit defaults; retry works; cross-tab review conflict preserves input and reports 409 accurately");

  await page.goto(`${server.base}/agent/new?id=${id}`, { waitUntil: "networkidle" });
  await page.getByRole("button", { name: /3 系统提示词/ }).click();
  assert.equal(await page.getByLabel("系统提示词", { exact: true }).inputValue(), created.agent.systemPrompt);
  await page.goto(`${server.base}/agent/new?template=rubric`, { waitUntil: "networkidle" });
  assert.equal(await page.getByLabel("智能体名称", { exact: true }).inputValue(), "表现性评价量规助手");
  await page.getByRole("button", { name: /3 系统提示词/ }).click();
  assert.ok((await page.getByLabel("系统提示词", { exact: true }).inputValue()).includes("信效度"));
  let newId;
  const firstSave = page.waitForResponse(res => res.url().endsWith("/api/agents") && res.request().method() === "POST");
  await page.getByRole("button", { name: "暂存草稿", exact: true }).click();
  newId = (await (await firstSave).json()).agent.id;
  await page.getByRole("status").filter({ hasText: "已创建" }).waitFor();
  const secondSave = page.waitForResponse(res => res.url().endsWith(`/api/agents/${newId}`) && res.request().method() === "PUT");
  await page.getByRole("button", { name: "暂存草稿", exact: true }).click();
  assert.ok((await secondSave).ok());
  pass("wizard template prefill, saved instruction reload and repeated save reuses one draft");

  await page.goto(`${server.base}/agent`, { waitUntil: "networkidle" });
  await root.getByRole("button", { name: /现有智能体/ }).click();
  await root.getByText("表现性评价量规助手", { exact: true }).waitFor();
  await page.screenshot({ path: join(results, "existing.png"), fullPage: true });
  await root.getByRole("button", { name: /场景助手/ }).click();
  for (const viewport of [{ width: 1280, height: 720 }, { width: 390, height: 844 }]) {
    await page.setViewportSize(viewport);
    await assertNoHorizontalOverflow(page, `agent ${viewport.width}`);
    await page.screenshot({ path: join(results, `viewport-${viewport.width}.png`), fullPage: true });
    await detail.click();
    const bounds = await dialog.boundingBox();
    assert.ok(bounds.x >= 0 && bounds.y >= 0 && bounds.x + bounds.width <= viewport.width + 1 && bounds.y + bounds.height <= viewport.height + 1);
    await dialog.getByRole("button", { name: "创建草稿并试用" }).scrollIntoViewIfNeeded();
    await page.screenshot({ path: join(results, `dialog-${viewport.width}.png`) });
    await dialog.getByRole("button", { name: "返回目录" }).click();
  }
  pass("existing directory retained, short desktop and mobile layouts, scrollable in-viewport dialogs");

  await page.route("**/api/agents", route => route.fulfill({ status: 503, json: { error: "offline" } }));
  await page.reload({ waitUntil: "networkidle" });
  await root.getByRole("alert").waitFor();
  assert.equal(await root.locator('[aria-label="现有智能体统计"] strong').first().innerText(), "--");
  await page.unroute("**/api/agents");
  await root.getByRole("button", { name: "重新加载" }).click();
  await root.getByRole("alert").waitFor({ state: "hidden" });
  pass("list failure never shows seed metrics and supports retry");
  assert.deepEqual(report.errors, []);
  pass("zero browser runtime errors");
} finally {
  writeFileSync(join(results, "report.json"), JSON.stringify(report, null, 2));
  await browser?.close();
  await server.cleanup();
  // Remove only this helper's generated include entries; preserve concurrent edits.
  const configPath = new URL("../tsconfig.json", import.meta.url);
  const current = JSON.parse(readFileSync(configPath, "utf8"));
  const original = JSON.parse(originalTsconfig);
  current.include = current.include.filter(path => !path.startsWith(".next-agent-workbench-ui-") || original.include.includes(path));
  writeFileSync(configPath, JSON.stringify(current, null, 2) + "\n");
  const nextEnvPath = new URL("../next-env.d.ts", import.meta.url);
  if (readFileSync(nextEnvPath, "utf8").includes(".next-agent-workbench-ui-")) writeFileSync(nextEnvPath, originalNextEnv);
}

// 角色/学段感知文案层（评审 P1-4 / summit H）：同组件、不同文案，避免每页各写一套而漂移。
// 防代写「学伴」引导按学段调语气，但都坚持「给思路、不给完整答案」。
import type { Stage } from "@/lib/types";

export const STAGE_LABEL: Record<Stage, string> = {
  primary: "小学",
  junior: "初中",
  senior: "高中",
};

// 学术诚信「学伴」引导：不改变【何时拦截】（分类逻辑在 classifyIntent，不动，杜绝代写口子），
// 只让【拦截后的引导文案】按学段 + 学科分化——写作类给"立意/细节/结构"、解题类给"审题/拆解/反推"，
// 避免对英语作文却问"这题考哪个知识点"这类语域错配（内测 P2-6）。纯模板，不依赖外部模型。
// [3a] P2 修复（内测）：学生贴出自己已写的句段时，把原句摘出来做针对性反馈起点。
// 只改「拦截后的引导文案」，不碰分类逻辑（何时拦截仍由 classifyIntent 决定，杜绝代写口子）。
function extractOwnDraft(message: string): string | null {
  const quoted = message.match(/[「"']([^」"']{10,90})[」"']/u) || message.match(/“([^”]{10,90})”/u);
  if (quoted) return quoted[1].trim();
  const after = message.match(/写了[：:]\s*(.{10,120}?)(?=\s*(?:请|帮我|麻烦|谢谢|但不要|不要)|[。！？\n]|$)/u);
  if (after) return after[1].trim();
  return null;
}

export function tutorScaffold(stage: Stage, message = ""): string {
  const isWriting = /作文|写作|文章|习作|读后感|观后感|议论文|记叙文|说明文|散文|周记|日记|写一篇|写一段|essay|composition|paragraph|\bwriting\b/i.test(message);
  if (isWriting) {
    // 针对性反馈（内测 [3a] P2）：学生已经写了句子却只收到通用步骤，会显得"没看学生的内容"。
    const ownDraft = extractOwnDraft(message);
    const draftEcho = ownDraft
      ? `\n\n你写的这句我看到了：「${ownDraft.slice(0, 80)}」——就从它开始改：把其中泛泛的评价词（如 beautiful / 很美 / 很好）换成 1-2 个能让人「看见」的具体画面或细节，再发我看看 👀`
      : "";
    switch (stage) {
      case "primary":
        return "写作文呀！我们像画画一样一步一步来～ 😊\n\n1. 🌟 **先想一件事**：你最想写的那个人、那件事或那个地方是什么？\n2. 👀 **加点细节**：它有什么样子、声音、味道？说 2-3 个能让我「看见」的小细节～\n3. ✏️ **自己写写看**：先写一两句发我，我帮你看怎么更生动！\n\n（我陪你想、帮你改，但不替你写整篇哦～）" + draftEcho;
      case "senior":
        return "写作值得好好打磨。与其代笔，不如把它拆成可迁移的方法：\n\n1. **立意**——你想表达的核心观点/情感是什么？能否用一句话概括并说明它为什么值得写？\n2. **论据 / 细节**——支撑它的具体事例、数据或感官细节有哪些？尽量避免空泛的形容词。\n3. **结构与逻辑**——开头如何切入、主体如何层层递进、结尾如何收束升华？先列个提纲。\n\n把你的立意、素材或初稿段落发我，我帮你检验逻辑、锤炼表达（不代写完整篇）。" + draftEcho;
      case "junior":
      default:
        return "写作这件事，我陪你把它写好，但不替你写整篇 😊 我们分几步：\n\n1. **先定中心**——这篇想表达的一个核心意思或感受，用一句话说说？\n2. **找具体**——围绕它，你能想到哪 2-3 个真实的细节、例子或画面？（具体的细节比「很美/很好」更打动人）\n3. **搭结构**——开头怎么引出、中间怎么展开、结尾怎么收？先列个小提纲。\n\n把你的中心句、细节、或写到一半的段落发我，我帮你看哪里能更具体、更有条理（不替你写整篇）。" + draftEcho;
    }
  }
  switch (stage) {
    case "primary":
      return "这个问题问得真好呀！我们像闯关一样一步步来好不好？😊\n\n1. 🧩 **先看看**：这道题在问什么？把你知道的告诉我～\n2. 👣 **走一小步**：我先带你做第一步……\n3. ✏️ **你来试**：接下来这步你想怎么做呢？\n\n先想一想、写一写，把过程发我，我陪你一起把它解开！";
    case "senior":
      return "好问题。与其直接给答案，不如把它拆成可迁移的方法：\n\n1. **审题**——本题考查的核心概念 / 模型是什么？已知与目标分别是？\n2. **切入**——我给出第一步的思路与依据，你接着往下推。\n3. **反推**——照此思路，下一步你打算如何展开？\n\n把你的思路或半成品发我，我帮你定位卡点、检验逻辑（不代写完整答案）。";
    case "junior":
    default:
      return "这是个好问题！不过答案直接给你，反而帮不到你 😊 我们一步一步来：\n\n1. **先拆解**——这题在考哪个知识点？说说你的已知和要求？\n2. **走第一步**——我先给你开个头的思路，剩下的你来接？\n3. **你来试**——按这个思路，下一步你打算怎么做？\n\n把你的思路、或写到一半的过程发我，我来帮你检查、点出卡在哪 👀（我不会替你写完整答案，但会陪你想明白）。";
  }
}
